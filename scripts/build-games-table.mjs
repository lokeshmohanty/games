// scripts/build-games-table.mjs — the room server's table of games: every
// game the arcade lists, and its kind, as worker/api/games.js.
//
// The account API must not take a game's id or kind from the player who
// reports it (an audit, 2026-11-15: any made-up id got a board, and the
// latest match's kind chose its order). So the Worker imports this
// table, generated from the same catalogs the site loads — lib/catalog.js
// (this repo's games, scripts/build-catalog.mjs) and community/catalog.js
// (the registry's pinned repos, scripts/fetch-community.mjs) — and refuses a
// result or a play count for any id not in it, or a result of another kind
// than its manifest's (worker/api/match.js). A manifest's "leaderboard"
// field is no longer read (no boards since 2026-11-25). Committed, like
// lib/catalog.js, so `wrangler deploy` bundles it as it is; `--check` fails
// when either catalog has moved on without it (`just test`, CI, and `just
// deploy-worker` before it deploys).
//
//   node scripts/build-games-table.mjs          write worker/api/games.js
//   node scripts/build-games-table.mjs --check  fail if it is out of date
//
// Needs community/ (`just community`): without it the table would silently
// lose every registry game, so it refuses instead.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { runInNewContext } from "node:vm";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Anything but --check is refused, as in build-catalog.mjs: a mistyped
// `--chek` would rewrite the table instead of checking it.
const unknown = process.argv.slice(2).filter((a) => a !== "--check");
if (unknown.length) {
	console.error(`build-games-table: unknown argument ${unknown.map((a) => `'${a}'`).join(", ")} — the only one is --check. To run several recipes, run them one per \`just\` call.`);
	process.exit(2);
}

/**
 * Games whose results come in more kinds than their manifest's one: the
 * results a game sends of each are accepted. Bubble Rush is "ffa" but its teams mode reports "teams"
 * (a review, 2026-11-16); so is Ludo, whose teams report "teams". Kept here
 * so it survives regeneration (a game not yet in a catalog is left out of the
 * table); a later manifest field ("kinds", docs/platform.md) would replace it.
 */
const EXTRA_KINDS = { "lokeshmohanty/bubble-rush": ["ffa", "teams"], "lokeshmohanty/ludo": ["ffa", "teams"] };
const OUT = join(ROOT, "worker", "api", "games.js");
const SOURCES = ["lib/catalog.js", "community/catalog.js"];

/** Every game a catalog script registers, listed or not: [{ id, kind }]. */
function gamesOf(file) {
	const path = join(ROOT, file);
	if (!existsSync(path)) {
		console.error(`${file} is missing: run \`just community\` first (the table would lose the registry's games)`);
		process.exit(1);
	}
	const NeonArcade = {};
	runInNewContext(readFileSync(path, "utf8"), { window: { NeonArcade }, NeonArcade, document: { baseURI: "http://x/" }, URL }, { filename: file });
	return [...(NeonArcade.CATALOG ?? []), ...(NeonArcade.UNLISTED ?? [])].map((g) => ({ id: g.id, kind: g.kind, title: g.title ?? g.name ?? null }));
}

const table = {};
const titles = {};
for (const file of SOURCES) {
	for (const { id, kind, title } of gamesOf(file)) {
		if (typeof id !== "string" || typeof kind !== "string") throw new Error(`${file}: a game without an id or a kind`);
		if (table[id] && table[id] !== kind) throw new Error(`${id} has two kinds: ${table[id]} and ${kind}`);
		table[id] = kind;
		if (typeof title === "string" && title.trim()) titles[id] ??= title.trim().slice(0, 60);
	}
}
const ids = Object.keys(table).sort();
const body = `// worker/api/games.js — GENERATED by scripts/build-games-table.mjs; do not edit.
// Every game the arcade lists (lib/catalog.js and community/catalog.js, listed
// or not) and its manifest's kind. The account API knows a game by this table
// only: results, play counts and the snapshot refuse any other id, and
// a result of another kind than its game's (worker/api/match.js). Regenerate
// after a game is added, removed or changes kind — \`just games-table\` — and
// before deploying the Worker (\`just deploy-worker\` checks it).

// No prototype: a looked-up id like "constructor" or "__proto__" is not a game.
export const GAMES = Object.assign(Object.create(null), {
${ids.map((id) => `\t${JSON.stringify(id)}: ${JSON.stringify(table[id])},`).join("\n")}
});

// The kinds of result a game may report, where more than its manifest's one
// (scripts/build-games-table.mjs EXTRA_KINDS).
export const KINDS = Object.assign(Object.create(null), ${JSON.stringify(Object.fromEntries(Object.entries(EXTRA_KINDS).filter(([id]) => table[id]).sort()), null, "\t")});

// Each game's title as its catalog writes it: the body of a party invite's
// notification (worker/api/social.js invite), never text a sender wrote.
export const TITLES = Object.assign(Object.create(null), {
${ids.filter((id) => titles[id]).map((id) => `\t${JSON.stringify(id)}: ${JSON.stringify(titles[id])},`).join("\n")}
});
`;

if (process.argv.includes("--check")) {
	const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
	if (now !== body) {
		console.error("worker/api/games.js is out of date: run `just games-table` (after `just community`)");
		process.exit(1);
	}
	console.log(`games table: ${ids.length} games, up to date`);
} else {
	writeFileSync(OUT, body);
	console.log(`games table: ${ids.length} games → worker/api/games.js`);
}
