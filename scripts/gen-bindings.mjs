/** Words wrapped to `width` columns, each line prefixed. */
function wrap(text, prefix, width = 80) {
	const lines = [];
	for (const para of String(text).split("\n")) {
		let line = "";
		for (const word of para.split(/\s+/).filter(Boolean)) {
			if (line && prefix.length + line.length + 1 + word.length > width) {
				lines.push(prefix + line);
				line = word;
			} else line = line ? `${line} ${word}` : word;
		}
		lines.push(line ? prefix + line : prefix.trimEnd());
	}
	return lines;
}

const messageDoc = (d) => joinDoc(`\`${d.message.t}\`, ${d.message.dir}.`, d.doc);
const declDoc = (d) => (d.message ? messageDoc(d) : d.doc);
const finish = (lines) => `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;

