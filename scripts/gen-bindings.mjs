// Python 3.11.

const PY_KEYWORDS = new Set(
	"False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield".split(" "),
);

function emitPy(m) {
	const out = [...HEADER.map((l) => `# ${l}`), ""];
	const esc = (s) => s.replaceAll("\\", "\\\\").replaceAll('"""', '\\"\\"\\"');
	out.push('"""', ...wrap(esc(m.doc), "", 79), "");
	out.push(
		...wrap(
			"Messages are TypedDicts: plain dicts to the json module. Optional fields are NotRequired. A message with a field named like a Python keyword (`from`, `as`) is declared with the functional TypedDict syntax. `reply` and `member` allow fields the schema does not name, which a TypedDict cannot say before Python 3.13.",
			"",
			79,
		),
		'"""',
		"",
		"from typing import Any, Literal, NotRequired, TypedDict",
		"",
	);
	const ty = (t) => {
		switch (t.k) {
			case "prim":
				return { string: "str", integer: "int", number: "float", boolean: "bool" }[t.p];
			case "json":
			case "ref":
			case "named":
				return t.name;
			case "any":
				return "Any";
			case "const":
				return `Literal[${t.value}]`;
			case "array":
				return `list[${ty(t.items)}]`;
			case "map":
				return `dict[str, ${ty(t.values)}]`;
			case "nullable":
				return `${ty(t.inner)} | None`;
		}
	};
	const doc = (text, indent = "") => (text ? wrap(text, `${indent}# `, 79) : []);
	const fieldType = (f) => (f.required ? ty(f.type) : `NotRequired[${ty(f.type)}]`);
	for (const d of m.order) {
		const text = declDoc(d);
		if (d.kind === "any") out.push(...doc(text), `${d.name} = Any`);
		else if (d.kind === "alias") out.push(...doc(text), `${d.name} = ${ty(d.target)}`);
		else if (d.kind === "enum") out.push(...doc(text), `${d.name} = Literal[${d.variants.map((v) => JSON.stringify(v.value)).join(", ")}]`);
		else if (d.kind === "union") out.push(...doc(text), `${d.name} = ${d.variants.map((v) => ty(v.type)).join(" | ")}`);
		else {
			const rows = [...(d.message ? [{ key: "v", type: "Literal[2]" }, { key: "t", type: `Literal[${JSON.stringify(d.message.t)}]` }] : []), ...d.fields.map((f) => ({ key: f.key, type: fieldType(f), doc: f.doc }))];
			if (rows.some((r) => PY_KEYWORDS.has(r.key))) {
				out.push(...doc(text), `${d.name} = TypedDict(`, `    ${JSON.stringify(d.name)},`, "    {");
				for (const r of rows) out.push(...doc(r.doc, "        "), `        ${JSON.stringify(r.key)}: ${r.type},`);
				out.push("    },", ")");
			} else {
				out.push(`class ${d.name}(TypedDict):`);
				if (text) out.push(...['"""', ...wrap(esc(text), "", 75), '"""'].map((l) => (l ? `    ${l}` : "")), "");
				for (const r of rows) out.push(...doc(r.doc, "    "), `    ${r.key}: ${r.type}`);
			}
		}
		out.push("", "");
	}
	for (const [name, konst, dir] of [["ToShell", "TO_SHELL", m.toShell], ["ToFrame", "TO_FRAME", m.toFrame]]) {
		out.push(...doc(`${dir.doc} Each message's t.`), `${name}Type = Literal[`, ...dir.list.map((x) => `    ${JSON.stringify(x.t)},`), "]", "");
		out.push(`${konst}: tuple[${name}Type, ...] = (`, ...dir.list.map((x) => `    ${JSON.stringify(x.t)},`), ")", "");
		out.push(...doc(dir.doc), `${name} = (`, ...dir.list.map((x, i) => `    ${i ? "| " : ""}${x.name}`), ")", "", "");
	}
	out.push("# Every message's t.", "MessageType = ToShellType | ToFrameType", "", "# Any message, either direction.", "Message = ToShell | ToFrame");
	return finish(out);
}

