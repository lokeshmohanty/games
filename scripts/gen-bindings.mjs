export function generate(schema) {
	const m = model(schema);
	return {
		"protocol.ts": emitTs(m),
		"protocol.rs": emitRs(m),
		"protocol.go": emitGo(m),
		"protocol.py": emitPy(m),
	};
}

function main() {
	const check = process.argv.includes("--check");
	let outputs;
	try {
		outputs = generate(JSON.parse(readFileSync(SCHEMA, "utf8")));
	} catch (err) {
		console.error(`gen-bindings: ${err.message}`);
		process.exit(2);
	}
	const stale = [];
	for (const [file, text] of Object.entries(outputs)) {
		const path = join(OUT, file);
		if (existsSync(path) && readFileSync(path, "utf8") === text) continue;
		stale.push(`${OUT_REL}/${file}`);
		if (!check) {
			mkdirSync(OUT, { recursive: true });
			writeFileSync(path, text);
		}
	}
	if (check) {
		if (stale.length) {
			console.error(`bindings are stale; run: node scripts/gen-bindings.mjs\n  ${stale.join("\n  ")}`);
			process.exit(1);
		}
		console.log(`${Object.keys(outputs).length} bindings in ${OUT_REL} match protocol.json`);
		return;
	}
	console.log(stale.length ? `wrote ${stale.join(", ")}` : `bindings in ${OUT_REL} unchanged`);
}

