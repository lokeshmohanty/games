// TypeScript.

function emitTs(m) {
	const out = [...HEADER.map((l) => `// ${l}`), "//", ...wrap(m.doc, "// "), ""];
	const doc = (text, indent = "") => {
		if (!text) return [];
		const body = wrap(text.replaceAll("*/", "*\\/"), `${indent} * `, 80);
		return body.length === 1 ? [`${indent}/** ${body[0].slice(indent.length + 3)} */`] : [`${indent}/**`, ...body, `${indent} */`];
	};
	const ty = (t) => {
		switch (t.k) {
			case "prim":
				return t.p === "string" ? "string" : t.p === "boolean" ? "boolean" : "number";
			case "json":
			case "ref":
			case "named":
				return t.name;
			case "any":
				return "unknown";
			case "const":
				return String(t.value);
			case "array": {
				const inner = ty(t.items);
				return /[ |]/.test(inner) ? `(${inner})[]` : `${inner}[]`;
			}
			case "map":
				return `Record<string, ${ty(t.values)}>`;
			case "nullable":
				return `${ty(t.inner)} | null`;
		}
	};
	for (const d of m.order) {
		out.push(...doc(declDoc(d)));
		if (d.kind === "any") out.push(`export type ${d.name} = unknown;`);
		else if (d.kind === "alias") out.push(`export type ${d.name} = ${ty(d.target)};`);
		else if (d.kind === "enum") out.push(`export type ${d.name} = ${d.variants.map((v) => JSON.stringify(v.value)).join(" | ")};`);
		else if (d.kind === "union") out.push(`export type ${d.name} = ${d.variants.map((v) => ty(v.type)).join(" | ")};`);
		else {
			out.push(`export interface ${d.name} {`);
			if (d.message) out.push("\tv: 2;", `\tt: ${JSON.stringify(d.message.t)};`);
			for (const f of d.fields) {
				out.push(...doc(f.doc, "\t"), `\t${f.key}${f.required ? "" : "?"}: ${ty(f.type)};`);
			}
			if (d.extra) out.push("\t/** Other fields are allowed. */", "\t[key: string]: unknown;");
			out.push("}");
		}
		out.push("");
	}
	for (const [name, dir] of [["ToShell", m.toShell], ["ToFrame", m.toFrame]]) {
		out.push(...doc(dir.doc), `export type ${name} =`, ...dir.list.map((x, i) => `\t| ${x.name}${i === dir.list.length - 1 ? ";" : ""}`), "");
	}
	out.push("/** Any message, either direction. */", "export type Message = ToShell | ToFrame;", "");
	out.push("/** Every message's `t`. */", 'export type MessageType = Message["t"];', "");
	for (const [konst, name, dir] of [["TO_SHELL", "ToShell", m.toShell], ["TO_FRAME", "ToFrame", m.toFrame]]) {
		out.push(`/** Every ${name} \`t\`, in schema order. */`, `export const ${konst}: readonly ${name}["t"][] = [`, ...dir.list.map((x) => `\t${JSON.stringify(x.t)},`), "];", "");
	}
	return finish(out);
}

