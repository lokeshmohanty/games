/** "MemberId" → "MemberID": Go's initialisms, word by word. */
const goIdent = (pascalName) => pascalName.replace(/[A-Z][a-z0-9]*/g, (w) => (["Id", "Json", "Sdk"].includes(w) ? w.toUpperCase() : w));

function emitGo(m) {
	const out = [...HEADER.map((l) => `// ${l}`), "", ...wrap(`Package arcade is the arcade's SDK v2 protocol: ${m.doc[0].toLowerCase()}${m.doc.slice(1)}`, "// "), "//"];
	out.push(
		...wrap(
			"Every message struct has its V and T fields; set V to Version and T to its Type constant. Optional fields are pointers (or nil slices and maps) left out when nil. DecodeToShell and DecodeToFrame read a message whatever its type.",
			"// ",
		),
	);
	out.push("package arcade", "", "import (", '\t"encoding/json"', '\t"errors"', '\t"fmt"', ")", "");
	const name = (n) => goIdent(n);
	const ty = (t) => {
		switch (t.k) {
			case "prim":
				return { string: "string", integer: "int", number: "float64", boolean: "bool" }[t.p];
			case "json":
			case "ref":
			case "named":
				return name(t.name);
			case "any":
				return "json.RawMessage";
			case "const":
				return "int";
			case "array":
				return `[]${ty(t.items)}`;
			case "map":
				return `map[string]${t.values.k === "any" ? "json.RawMessage" : ty(t.values)}`;
			case "nullable":
				return nilable(t.inner) ? ty(t.inner) : `*${ty(t.inner)}`;
		}
	};
	const nilable = (t) => t.k === "array" || t.k === "map" || t.k === "any" || t.k === "json" || t.k === "nullable";
	const doc = (text, indent = "") => (text ? wrap(text, `${indent}// `) : []);
	const typeConst = (x) => `Type${name(x.name)}`;

	out.push("// Version is every message's v.", "const Version = 2", "");
	out.push("// Each message's t.", "const (");
	const all = [...m.toShell.list, ...m.toFrame.list.filter((x) => !m.toShell.list.some((y) => y.t === x.t))];
	for (const x of all) out.push(`\t${typeConst(x)} = ${JSON.stringify(x.t)}`);
	out.push(")", "");
	for (const [varName, dir] of [["ToShellTypes", m.toShell], ["ToFrameTypes", m.toFrame]]) {
		out.push(`// ${varName} lists every t that goes ${dir === m.toShell ? "frame to shell" : "shell to frame"}, in schema order.`);
		out.push(`var ${varName} = [...]string{`, ...dir.list.map((x) => `\t${typeConst(x)},`), "}", "");
	}

	for (const d of m.order) {
		const n = name(d.name);
		const text = declDoc(d);
		out.push(...doc(text ? `${n}: ${text}` : n));
		if (d.kind === "any") out.push(`type ${n} = json.RawMessage`);
		else if (d.kind === "alias") out.push(`type ${n} = ${ty(d.target)}`);
		else if (d.kind === "enum") {
			out.push(`type ${n} string`, "", `// ${n} values.`, "const (");
			for (const v of d.variants) out.push(`\t${n}${v.name} ${n} = ${JSON.stringify(v.value)}`);
			out.push(")");
		} else if (d.kind === "union") {
			out.push(`// Exactly one field is set.`, `type ${n} struct {`);
			for (const v of d.variants) out.push(...doc(v.doc, "\t"), `\t${v.name} ${v.type.k === "array" ? ty(v.type) : `*${ty(v.type)}`}`);
			out.push("}", "");
			out.push(`func (u ${n}) MarshalJSON() ([]byte, error) {`, "\tswitch {");
			for (const v of d.variants) out.push(`\tcase u.${v.name} != nil:`, `\t\treturn json.Marshal(u.${v.name})`);
			out.push("\t}", `\treturn nil, errors.New("arcade: ${n} has no field set")`, "}", "");
			out.push(`func (u *${n}) UnmarshalJSON(b []byte) error {`, `\t*u = ${n}{}`, '\tif string(b) == "null" {', `\t\treturn errors.New("arcade: ${n} cannot be null")`, "\t}");
			for (const v of d.variants) {
				const isArr = v.type.k === "array";
				out.push(`\tvar ${v.name.toLowerCase()} ${ty(v.type)}`, `\tif json.Unmarshal(b, &${v.name.toLowerCase()}) == nil {`, `\t\tu.${v.name} = ${isArr ? "" : "&"}${v.name.toLowerCase()}`, "\t\treturn nil", "\t}");
			}
			out.push(`\treturn fmt.Errorf("arcade: %s is not a ${n}", b)`, "}");
		} else {
			out.push(`type ${n} struct {`);
			const fields = new Set();
			const row = (field, type, tag) => {
				if (fields.has(field)) fail(d.path, `two Go fields would be named ${field}`);
				fields.add(field);
				out.push(`\t${field} ${type} \`json:"${tag}"\``);
			};
			if (d.message) {
				out.push("\t// Version.");
				row("V", "int", "v");
				out.push(`\t// ${typeConst(d)}.`);
				row("T", "string", "t");
			}
			for (const f of d.fields) {
				out.push(...doc(f.doc, "\t"));
				const field = goIdent(pascal(f.key));
				if (f.required) row(field, ty(f.type), f.key);
				else row(field, nilable(f.type) ? ty(f.type) : `*${ty(f.type)}`, `${f.key},omitempty`);
			}
			if (d.extra) {
				out.push("\t// Fields the schema does not name; it allows any.");
				row("Extra", "map[string]json.RawMessage", "-");
			}
			out.push("}");
			if (d.extra) {
				const keys = [...(d.message ? ["v", "t"] : []), ...d.fields.map((f) => f.key)];
				out.push(
					"",
					`// MarshalJSON writes Extra's fields beside the named ones.`,
					`func (m ${n}) MarshalJSON() ([]byte, error) {`,
					`\ttype plain ${n}`,
					"\tb, err := json.Marshal(plain(m))",
					"\tif err != nil || len(m.Extra) == 0 {",
					"\t\treturn b, err",
					"\t}",
					"\tall := map[string]json.RawMessage{}",
					"\tif err := json.Unmarshal(b, &all); err != nil {",
					"\t\treturn nil, err",
					"\t}",
					"\tfor k, v := range m.Extra {",
					"\t\tif _, named := all[k]; !named {",
					"\t\t\tall[k] = v",
					"\t\t}",
					"\t}",
					"\treturn json.Marshal(all)",
					"}",
					"",
					`// UnmarshalJSON keeps the fields the schema does not name in Extra.`,
					`func (m *${n}) UnmarshalJSON(b []byte) error {`,
					`\ttype plain ${n}`,
					"\tif err := json.Unmarshal(b, (*plain)(m)); err != nil {",
					"\t\treturn err",
					"\t}",
					"\tvar all map[string]json.RawMessage",
					"\tif err := json.Unmarshal(b, &all); err != nil {",
					"\t\treturn err",
					"\t}",
					`\tfor _, k := range [...]string{${keys.map((k) => JSON.stringify(k)).join(", ")}} {`,
					"\t\tdelete(all, k)",
					"\t}",
					"\tm.Extra = nil",
					"\tif len(all) > 0 {",
					"\t\tm.Extra = all",
					"\t}",
					"\treturn nil",
					"}",
				);
			}
		}
		out.push("");
	}

	out.push(
		"// Envelope is what every message shares: decode it to see what a message is.",
		"type Envelope struct {",
		'\tV int    `json:"v"`',
		'\tT string `json:"t"`',
		"}",
		"",
		"// ErrUnknownType wraps a t this version does not know. The protocol says to",
		"// ignore such a message: the other side may be newer.",
		'var ErrUnknownType = errors.New("arcade: unknown message type")',
		"",
	);
	for (const [fn, dir, what] of [["DecodeToShell", m.toShell, "frame-to-shell"], ["DecodeToFrame", m.toFrame, "shell-to-frame"]]) {
		out.push(
			`// ${fn} reads a ${what} message into a pointer to its struct (*${name(dir.list[0].name)}, ...).`,
			`func ${fn}(b []byte) (any, error) {`,
			"\tvar e Envelope",
			"\tif err := json.Unmarshal(b, &e); err != nil {",
			"\t\treturn nil, err",
			"\t}",
			"\tif e.V != Version {",
			'\t\treturn nil, fmt.Errorf("arcade: message v %d, want %d", e.V, Version)',
			"\t}",
			"\tvar m any",
			"\tswitch e.T {",
		);
		for (const x of dir.list) out.push(`\tcase ${typeConst(x)}:`, `\t\tm = &${name(x.name)}{}`);
		out.push("\tdefault:", '\t\treturn nil, fmt.Errorf("%w: %q", ErrUnknownType, e.T)', "\t}", "\tif err := json.Unmarshal(b, m); err != nil {", "\t\treturn nil, err", "\t}", "\treturn m, nil", "}", "");
	}
	return gofmtAlign(finish(out));
}

/**
 * gofmt's alignment of struct fields and const blocks: in each run of
 * consecutive `\tName Type `tag`` lines (a comment line or blank ends the run),
 * pad names and types to a common width. Keeps the output `gofmt -l` clean.
 */
function gofmtAlign(text) {
	const lines = text.split("\n");
	const cells = (l) => {
		let m = /^\t([A-Za-z_][A-Za-z0-9_]*) (\S.*?) (`.*`)$/.exec(l);
		if (m) return [m[1], m[2], m[3]];
		m = /^\t([A-Za-z_][A-Za-z0-9_]*) ([A-Za-z_][A-Za-z0-9_]*) (= .*)$/.exec(l);
		if (m) return [m[1], m[2], m[3]];
		m = /^\t([A-Za-z_][A-Za-z0-9_]*) (= .*)$/.exec(l);
		if (m) return [m[1], m[2]];
		return null;
	};
	for (let i = 0; i < lines.length; ) {
		const first = cells(lines[i]);
		if (!first) {
			i++;
			continue;
		}
		let j = i;
		const run = [];
		while (j < lines.length) {
			const c = cells(lines[j]);
			if (!c || c.length !== first.length) break;
			run.push(c);
			j++;
		}
		const widths = first.map((_, k) => Math.max(...run.map((c) => c[k].length)));
		run.forEach((c, r) => {
			lines[i + r] = `\t${c.map((cell, k) => (k === c.length - 1 ? cell : cell.padEnd(widths[k]))).join(" ")}`;
		});
		i = j;
	}
	return lines.join("\n");
}

