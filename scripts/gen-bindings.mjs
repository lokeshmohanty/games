// scripts/gen-bindings.mjs — sdk/v2/protocol.json as types, in four languages.
//
// The wire is the API (protocol.json): a game in Rust, Go or Python is
// anything that reads and writes those messages. Copying forty message shapes
// into each language by hand would drift from the schema on the first edit,
// so this reads the schema and writes sdk/v2/bindings/protocol.{ts,rs,go,py},
// and `just test` fails when they no longer match it.
//
// It understands the JSON Schema protocol.json is written in and nothing
// more. Anything else — a new keyword, a type list it cannot map, a `$ref`
// with siblings — throws with the schema path, rather than quietly turning
// into an untyped field in four languages.
//
//   node scripts/gen-bindings.mjs           rewrite the bindings
//   node scripts/gen-bindings.mjs --check   exit 1, listing them, if any is stale
//
// The output is a pure function of protocol.json (no dates, no versions), so
// --check is a byte comparison.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA = join(ROOT, "sdk", "v2", "protocol.json");
const OUT = join(ROOT, "sdk", "v2", "bindings");
const OUT_REL = "sdk/v2/bindings";

const HEADER = [
	"GENERATED by scripts/gen-bindings.mjs from sdk/v2/protocol.json — do not edit.",
	"Regenerate with `node scripts/gen-bindings.mjs` (`just bindings`).",
];

// ---------------------------------------------------------------------------
// The schema, read into a small model: named types in dependency order.
//
//   type nodes   { k: "prim", p }        string | integer | number | boolean
//                { k: "json", name }     a $ref to a def that is any JSON value
//                { k: "any" }            an inline schema with no constraints
//                { k: "const", value }   an integer const (v, hello.sdk)
//                { k: "named", name }    a struct, enum or union declared below
//                { k: "ref", name }      a shared def (struct or alias)
//                { k: "array", items }   { k: "map", values }   { k: "nullable", inner }
//
//   declarations { kind: "any" | "alias" | "enum" | "union" | "struct", name, doc, ... }

const ANNOTATIONS = new Set(["description", "title", "$comment"]);
const LIMITS = { minimum: "num", maximum: "num", minLength: "string", maxLength: "string", minItems: "array", maxItems: "array" };
const SHAPES = new Set(["$ref", "type", "const", "enum", "properties", "required", "additionalProperties", "items", "oneOf"]);
const PRIMS = new Set(["string", "integer", "number", "boolean"]);
const IDENT = /^[A-Za-z][A-Za-z0-9]*$/;

function fail(path, why) {
	throw new Error(`protocol.json ${path}: ${why}`);
}

const isObject = (x) => typeof x === "object" && x !== null && !Array.isArray(x);
const isAny = (s) => Object.keys(s).every((k) => ANNOTATIONS.has(k));
const isNull = (s) => isObject(s) && s.type === "null" && Object.keys(s).every((k) => k === "type" || ANNOTATIONS.has(k));

/** "store.set" → "StoreSet", "memberId" → "MemberId". */
function pascal(name, path) {
	const parts = name.split(".");
	if (!parts.every((p) => IDENT.test(p))) fail(path, `"${name}" cannot be a type name (letters and digits, dot-separated)`);
	return parts.map((p) => p[0].toUpperCase() + p.slice(1)).join("");
}

/** Every keyword is one this file maps, and fits the kind of schema it is on. */
function checkKeys(s, path, shapes) {
	if (!isObject(s)) fail(path, "a schema must be an object");
	const kind = s.type === "integer" || s.type === "number" ? "num" : s.type;
	for (const k of Object.keys(s)) {
		if (ANNOTATIONS.has(k)) continue;
		if (k in LIMITS) {
			if (LIMITS[k] !== kind) fail(path, `"${k}" on a schema that is not ${LIMITS[k] === "num" ? "an integer or number" : `a${LIMITS[k] === "array" ? "n" : ""} ${LIMITS[k]}`}`);
			continue;
		}
		if (!SHAPES.has(k)) fail(path, `unsupported keyword "${k}"`);
		if (!shapes.includes(k)) fail(path, `"${k}" alongside ${shapes.filter((x) => x in s).join(", ") || "nothing it applies to"}`);
	}
}

/** The validation-only keywords, as a sentence for the doc comment. */
function limitsNote(s) {
	const range = (lo, hi, unit) => {
		if (lo !== undefined && hi !== undefined) return lo === hi ? `Exactly ${lo}${unit}.` : `${lo}..${hi}${unit}.`;
		if (lo !== undefined) return `At least ${lo}${unit}.`;
		if (hi !== undefined) return `At most ${hi}${unit}.`;
		return "";
	};
	const notes = [
		range(s.minimum, s.maximum, ""),
		range(s.minLength, s.maxLength, " chars"),
		range(s.minItems, s.maxItems, " items"),
	].filter(Boolean);
	if (isObject(s.items)) {
		const each = limitsNote(s.items);
		if (each) notes.push(`Each: ${each}`);
	}
	return notes.join(" ");
}

const joinDoc = (...parts) => parts.filter(Boolean).join(" ");

function model(schema) {
	for (const k of Object.keys(schema)) {
		if (!["$schema", "$id", "title", "description", "oneOf", "$defs"].includes(k)) fail("#", `unsupported top-level keyword "${k}"`);
	}
	const defs = isObject(schema.$defs) ? schema.$defs : fail("#", "no $defs");
	const refName = (s, path) => {
		if (!isObject(s) || typeof s.$ref !== "string") fail(path, "expected a $ref");
		return (/^#\/\$defs\/([^/]+)$/.exec(s.$ref) ?? fail(path, `$ref "${s.$ref}" is not #/$defs/<name>`))[1];
	};
	const root = (schema.oneOf ?? []).map((s, i) => refName(s, `#/oneOf/${i}`));
	if (root.join() !== "toShell,toFrame") fail("#/oneOf", "must be [toShell, toFrame]");

	// The two directions: each a oneOf of $refs to message defs.
	const dirs = {};
	for (const dir of ["toShell", "toFrame"]) {
		const path = `#/$defs/${dir}`;
		const d = defs[dir] ?? fail(path, "missing");
		if (!Object.keys(d).every((k) => k === "oneOf" || ANNOTATIONS.has(k)) || !Array.isArray(d.oneOf)) fail(path, "must be only a oneOf of $refs");
		const names = d.oneOf.map((s, i) => {
			if (Object.keys(s).length !== 1) fail(`${path}/oneOf/${i}`, "must be a bare $ref");
			const n = refName(s, `${path}/oneOf/${i}`);
			if (!(n in defs)) fail(`${path}/oneOf/${i}`, `$ref to missing def "${n}"`);
			return n;
		});
		if (new Set(names).size !== names.length) fail(path, "lists a message twice");
		dirs[dir] = { doc: d.description ?? "", names };
	}
	const messages = new Set([...dirs.toShell.names, ...dirs.toFrame.names]);

	const types = new Map();
	const order = [];
	const state = new Map();
	const intConsts = new Set();
	const add = (decl) => {
		if (types.has(decl.name)) fail(decl.path, `two types would be named ${decl.name}`);
		types.set(decl.name, decl);
		order.push(decl);
	};

	/** A shared def, declared (with what it refers to first) on first use. */
	function shared(name, from) {
		if (!(name in defs)) fail(from, `$ref to missing def "${name}"`);
		if (name === "toShell" || name === "toFrame") fail(from, `a field cannot be a whole direction ("${name}")`);
		if (messages.has(name)) fail(from, `a field refers to the message "${name}"`);
		const tname = pascal(name, `#/$defs/${name}`);
		if (state.get(name) === "busy") fail(from, `cyclic $ref through "${name}"`);
		if (!state.has(name)) {
			state.set(name, "busy");
			sharedDef(name, tname);
			state.set(name, "done");
		}
		return tname;
	}

	function sharedDef(name, tname) {
		const s = defs[name];
		const path = `#/$defs/${name}`;
		if (!isObject(s)) fail(path, "a schema must be an object");
		if (isAny(s)) return add({ kind: "any", name: tname, doc: s.description ?? "", path });
		if (isObject(s.properties) && isObject(s.properties.t) && "const" in s.properties.t) {
			fail(path, "looks like a message (t is a const) but is in neither toShell nor toFrame");
		}
		if (s.type === "object") return struct(s, tname, path, null);
		if (PRIMS.has(s.type)) {
			checkKeys(s, path, ["type"]);
			return add({ kind: "alias", name: tname, target: { k: "prim", p: s.type }, doc: joinDoc(s.description, limitsNote(s)), path });
		}
		fail(path, "a shared def must be an object, a string/integer/number/boolean, or unconstrained (any JSON)");
	}

	function struct(s, name, path, message) {
		checkKeys(s, path, ["type", "properties", "required", "additionalProperties"]);
		const props = s.properties;
		if (!isObject(props)) fail(path, "an object type needs properties");
		const required = new Set(s.required ?? []);
		for (const r of required) if (!(r in props)) fail(path, `requires "${r}", which is not a property`);
		const ap = s.additionalProperties;
		if (ap !== undefined && ap !== true) fail(path, "additionalProperties beside properties must be true or absent");
		const fields = [];
		for (const [key, ps] of Object.entries(props)) {
			const fpath = `${path}/properties/${key}`;
			if (!IDENT.test(key)) fail(fpath, `"${key}" cannot be a field name`);
			if (message && (key === "v" || key === "t")) continue;
			const type = typeOf(ps, fpath, name + pascal(key, fpath));
			fields.push({ key, type, required: required.has(key), doc: joinDoc(isObject(ps) ? ps.description : "", isObject(ps) && !ps.$ref ? limitsNote(ps) : "", carriesJson(type) ? "May carry ArrayBuffers (see Json)." : "") });
		}
		add({ kind: "struct", name, doc: s.description ?? "", fields, extra: ap === true, message, path });
	}

	function enumOf(values, name, path, doc) {
		if (!Array.isArray(values) || !values.length || !values.every((v) => typeof v === "string")) fail(path, "only non-empty enums of strings are supported");
		if (new Set(values).size !== values.length) fail(path, "enum lists a value twice");
		const variants = values.map((value) => {
			if (value !== "" && !IDENT.test(value)) fail(path, `enum value "${value}" cannot be a variant name`);
			return { value, name: value === "" ? "Empty" : value[0].toUpperCase() + value.slice(1) };
		});
		add({ kind: "enum", name, variants, doc, path });
		return { k: "named", name };
	}

	function typeOf(s, path, hint) {
		if (!isObject(s)) fail(path, "a schema must be an object");
		for (const k of Object.keys(s)) if (!ANNOTATIONS.has(k) && !(k in LIMITS) && !SHAPES.has(k)) fail(path, `unsupported keyword "${k}"`);
		if ("$ref" in s) {
			const sibling = Object.keys(s).find((k) => k !== "$ref" && !ANNOTATIONS.has(k));
			if (sibling) fail(path, `"${sibling}" beside $ref (only annotations may sit there)`);
			const tname = shared(refName(s, path), path);
			return types.get(tname).kind === "any" ? { k: "json", name: tname } : { k: "ref", name: tname };
		}
		if (isAny(s)) return { k: "any" };
		if ("const" in s) {
			checkKeys(s, path, ["const"]);
			if (typeof s.const === "string") return enumOf([s.const], hint, path, `The only value of ${hint}.`);
			if (Number.isInteger(s.const) && s.const >= 0) {
				intConsts.add(s.const);
				return { k: "const", value: s.const };
			}
			fail(path, "only string and non-negative integer consts are supported");
		}
		if ("enum" in s) {
			checkKeys(s, path, ["enum", "type"]);
			if (s.type !== undefined && s.type !== "string") fail(path, "an enum must be of strings");
			return enumOf(s.enum, hint, path, `Values of ${hint}.`);
		}
		if ("oneOf" in s) {
			checkKeys(s, path, ["oneOf"]);
			const alts = s.oneOf;
			if (!Array.isArray(alts) || alts.length < 2) fail(path, "oneOf needs two or more schemas");
			const nulls = alts.filter(isNull).length;
			if (nulls === 1 && alts.length === 2) {
				const i = alts.findIndex((a) => !isNull(a));
				return { k: "nullable", inner: typeOf(alts[i], `${path}/oneOf/${i}`, hint) };
			}
			if (nulls) fail(path, "null in a oneOf is supported only as one of exactly two schemas");
			const variants = alts.map((a, i) => {
				const vpath = `${path}/oneOf/${i}`;
				const type = typeOf(a, vpath, `${hint}${i}`);
				const base = type.k === "array" ? type.items : type;
				if (!(base.k === "prim" || base.k === "ref")) fail(vpath, "a oneOf variant must be a primitive, a $ref, or an array of one");
				const name = a.title ?? (type.k === "array" ? `${variantName(base)}Array` : variantName(base));
				if (!IDENT.test(name)) fail(vpath, `"${name}" cannot be a variant name (set a title)`);
				return { name, type, doc: joinDoc(a.description, limitsNote(a)) };
			});
			if (new Set(variants.map((v) => v.name)).size !== variants.length) fail(path, "two oneOf variants would share a name (set titles)");
			add({ kind: "union", name: hint, variants, doc: `One of: ${variants.map((v) => v.name).join(", ")}.`, path });
			return { k: "named", name: hint };
		}
		if (Array.isArray(s.type)) {
			const others = s.type.filter((t) => t !== "null");
			if (s.type.length !== 2 || others.length !== 1) fail(path, `type list ${JSON.stringify(s.type)}: only [<type>, "null"] is supported`);
			return { k: "nullable", inner: typeOf({ ...s, type: others[0] }, path, hint) };
		}
		if (PRIMS.has(s.type)) {
			checkKeys(s, path, ["type"]);
			return { k: "prim", p: s.type };
		}
		if (s.type === "array") {
			checkKeys(s, path, ["type", "items"]);
			if (!isObject(s.items)) fail(path, "an array needs an items schema");
			return { k: "array", items: typeOf(s.items, `${path}/items`, `${hint}Item`) };
		}
		if (s.type === "object") {
			if (s.properties !== undefined) {
				struct(s, hint, path, null);
				return { k: "named", name: hint };
			}
			checkKeys(s, path, ["type", "additionalProperties"]);
			const ap = s.additionalProperties;
			if (ap === undefined || ap === true) return { k: "map", values: { k: "any" } };
			if (ap === false) fail(path, "an object with no properties and additionalProperties false");
			return { k: "map", values: typeOf(ap, `${path}/additionalProperties`, `${hint}Value`) };
		}
		if (s.type === "null") fail(path, 'type "null" is supported only as the other half of a nullable');
		fail(path, s.type === undefined ? "no type, $ref, const, enum or oneOf" : `unsupported type "${s.type}"`);
	}

	function variantName(t) {
		return t.k === "prim" ? t.p[0].toUpperCase() + t.p.slice(1) : t.name;
	}

	function message(name) {
		const s = defs[name];
		const path = `#/$defs/${name}`;
		if (!isObject(s) || s.type !== "object" || !isObject(s.properties)) fail(path, "a message must be an object with properties");
		const req = s.required ?? [];
		if (!req.includes("v") || !req.includes("t")) fail(path, "a message must require v and t");
		const { v, t } = s.properties;
		const bareConst = (x) => isObject(x) && Object.keys(x).every((k) => k === "const" || ANNOTATIONS.has(k));
		if (!bareConst(v) || v.const !== 2) fail(`${path}/properties/v`, "must be { const: 2 }");
		if (!bareConst(t) || t.const !== name) fail(`${path}/properties/t`, `must be { const: "${name}" } (a message def is named after its t)`);
		intConsts.add(2);
		const dir = dirs.toShell.names.includes(name) ? (dirs.toFrame.names.includes(name) ? "either direction" : "frame to shell") : "shell to frame";
		struct(s, pascal(name, path), path, { t: name, dir });
	}

	for (const name of Object.keys(defs)) {
		if (name === "toShell" || name === "toFrame") continue;
		if (messages.has(name)) message(name);
		else shared(name, `#/$defs/${name}`);
	}

	const json = order.find((d) => d.kind === "any");
	if (!json) fail("#/$defs", "no any-JSON def (the json def) to name payloads after");
	const named = (dir) => dirs[dir].names.map((n) => ({ t: n, name: pascal(n) }));
	return {
		doc: schema.description ?? "",
		order,
		types,
		json: json.name,
		intConsts: [...intConsts].sort((a, b) => a - b),
		toShell: { doc: dirs.toShell.doc, list: named("toShell") },
		toFrame: { doc: dirs.toFrame.doc, list: named("toFrame") },
		messages: order.filter((d) => d.message),
	};
}

function carriesJson(t) {
	if (t.k === "json" || t.k === "any") return true;
	if (t.k === "array") return carriesJson(t.items);
	if (t.k === "map") return carriesJson(t.values);
	if (t.k === "nullable") return carriesJson(t.inner);
	return false;
}

