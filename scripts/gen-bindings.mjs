const RUST_KEYWORDS = new Set(
	"as async await break const continue crate dyn else enum extern false fn for gen if impl in let loop match mod move mut pub ref return self static struct super trait true try type unsafe use where while yield abstract become box do final macro override priv typeof unsized virtual".split(" "),
);

// Names a glob import (`use protocol::*`) would shadow: std's prelude, and what
// this file imports. A type named so gets `Message` appended (`result` →
// `ResultMessage`, `send` → `SendMessage`); enum variants keep the plain name.
const RUST_TAKEN = new Set(
	"AsMut AsRef BTreeMap Box Clone Copy Default Deserialize DoubleEndedIterator Drop Eq Err ExactSizeIterator Extend Fn FnMut FnOnce From FromIterator Into IntoIterator Iterator None Ok Option Ord PartialEq PartialOrd Result Send Serialize Sized Some String Sync ToOwned ToString TryFrom TryInto Unpin Vec".split(" "),
);
const rsName = (name) => (RUST_TAKEN.has(name) ? `${name}Message` : name);

function emitRs(m) {
	const out = [...HEADER.map((l) => `// ${l}`), "//", ...wrap(m.doc, "// ", 100), "//"];
	const renamed = m.order.filter((d) => RUST_TAKEN.has(d.name)).map((d) => `\`${rsName(d.name)}\``);
	out.push(
		...wrap(
			`Each message struct holds everything but \`t\`: the \`ToShell\` and \`ToFrame\` enums carry it as their serde tag, so serialise a message through its enum (a bare struct has no \`t\`). \`v\` is a \`V2\` field, which writes 2 and refuses anything else. Optional fields are \`Option\`s, left out when \`None\`; a field that is both optional and nullable reads null and absent alike as \`None\`.${renamed.length ? ` ${renamed.join(" and ")} have \`Message\` appended so that \`use protocol::*\` does not shadow std's prelude.` : ""} Plain \`//\` comments up here so the file also works through \`include!\`.`,
			"// ",
			100,
		),
		"",
	);
	const uses = { btree: false };
	const ty = (t) => {
		switch (t.k) {
			case "prim":
				return { string: "String", integer: "i64", number: "f64", boolean: "bool" }[t.p];
			case "json":
			case "ref":
			case "named":
				return rsName(t.name);
			case "any":
				return "serde_json::Value";
			case "const":
				return `V${t.value}`;
			case "array":
				return `Vec<${ty(t.items)}>`;
			case "map":
				if (t.values.k === "any") return "serde_json::Map<String, serde_json::Value>";
				uses.btree = true;
				return `BTreeMap<String, ${ty(t.values)}>`;
			case "nullable":
				return `Option<${ty(t.inner)}>`;
		}
	};
	const doc = (text, indent = "") => (text ? wrap(text, `${indent}/// `, 100) : []);
	const derive = "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]";
	const body = [];
	for (const n of m.intConsts) {
		const what = n === 2 ? "the protocol version every message carries as `v` (and `hello` as `sdk`)" : `a const ${n}`;
		body.push(
			...doc(`The integer ${n}: ${what}. Serialises as \`${n}\`; deserialising any other value is an error.`),
			"#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]",
			`pub struct V${n};`,
			"",
			`impl Serialize for V${n} {`,
			"    fn serialize<S: serde::Serializer>(&self, s: S) -> core::result::Result<S::Ok, S::Error> {",
			`        s.serialize_u64(${n})`,
			"    }",
			"}",
			"",
			`impl<'de> Deserialize<'de> for V${n} {`,
			"    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> core::result::Result<Self, D::Error> {",
			"        match u64::deserialize(d)? {",
			`            ${n} => core::result::Result::Ok(V${n}),`,
			"            other => {",
			`                let msg = format!("expected ${n}, got {other}");`,
			"                core::result::Result::Err(<D::Error as serde::de::Error>::custom(msg))",
			"            }",
			"        }",
			"    }",
			"}",
			"",
		);
	}
	for (const d of m.order) {
		const name = rsName(d.name);
		body.push(...doc(declDoc(d)));
		if (d.kind === "any") body.push(`pub type ${name} = serde_json::Value;`);
		else if (d.kind === "alias") body.push(`pub type ${name} = ${ty(d.target)};`);
		else if (d.kind === "enum") {
			body.push("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]", `pub enum ${name} {`);
			for (const v of d.variants) body.push(`    #[serde(rename = ${JSON.stringify(v.value)})]`, `    ${v.name},`);
			body.push("}");
		} else if (d.kind === "union") {
			body.push(derive, "#[serde(untagged)]", `pub enum ${name} {`);
			for (const v of d.variants) body.push(...doc(v.doc, "    "), `    ${v.name}(${ty(v.type)}),`);
			body.push("}");
		} else {
			body.push(derive, `pub struct ${name} {`);
			const names = new Set();
			if (d.message) {
				body.push("    pub v: V2,");
				names.add("v");
			}
			for (const f of d.fields) {
				let name = f.key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
				if (RUST_KEYWORDS.has(name)) name += "_";
				if (names.has(name)) fail(d.path, `two Rust fields would be named ${name}`);
				names.add(name);
				body.push(...doc(f.doc, "    "));
				const attrs = [];
				if (name !== f.key) attrs.push(`rename = ${JSON.stringify(f.key)}`);
				let type = ty(f.type);
				if (!f.required) {
					attrs.push('skip_serializing_if = "Option::is_none"', "default");
					if (f.type.k !== "nullable") type = `Option<${type}>`;
				}
				if (attrs.length) body.push(`    #[serde(${attrs.join(", ")})]`);
				body.push(`    pub ${name}: ${type},`);
			}
			if (d.extra) {
				if (names.has("extra")) fail(d.path, "a field named extra clashes with the extra-fields map");
				body.push("    /// Fields the schema does not name; it allows any.", "    #[serde(flatten)]", "    pub extra: serde_json::Map<String, serde_json::Value>,");
			}
			body.push("}");
		}
		body.push("");
	}
	for (const [name, dir] of [["ToShell", m.toShell], ["ToFrame", m.toFrame]]) {
		// `init` dwarfs the rest, but boxing it would cost every reader a deref for clippy's sake.
		body.push(...doc(dir.doc), derive, "#[allow(clippy::large_enum_variant)]", '#[serde(tag = "t")]', `pub enum ${name} {`);
		for (const x of dir.list) body.push(`    #[serde(rename = ${JSON.stringify(x.t)})]`, `    ${x.name}(${rsName(x.name)}),`);
		body.push(
			"    /// A `t` this version does not know. The protocol says to ignore it (the other side may be",
			"    /// newer); it cannot be serialised.",
			"    #[serde(other, skip_serializing)]",
			"    Unknown,",
			"}",
			"",
		);
	}
	for (const [konst, name, dir] of [["TO_SHELL", "ToShell", m.toShell], ["TO_FRAME", "ToFrame", m.toFrame]]) {
		body.push(`/// Every ${name} \`t\`, in schema order.`, `pub const ${konst}: &[&str] = &[`, ...dir.list.map((x) => `    ${JSON.stringify(x.t)},`), "];", "");
	}
	out.push("use serde::{Deserialize, Serialize};");
	if (uses.btree) out.push("use std::collections::BTreeMap;");
	out.push("", ...body);
	return finish(out);
}

