// scripts/catalog-lib.mjs — turning game.json manifests into the scripts the
// site loads. Shared by build-catalog.mjs (first-party, committed) and
// fetch-community.mjs (pinned outside repos, generated at deploy).

import { readFileSync } from "node:fs";
import { dirname, relative } from "node:path";
import { validateContributor, validateManifest } from "./manifest.mjs";

/**
 * Catalog entries for manifest files. `owner` namespaces community ids
 * (<owner>/<id>); `root` is the site root paths are made relative to.
 * Throws with every problem listed when any manifest is invalid.
 */
export function catalogEntries(files, root) {
	const games = [];
	const errors = [];
	for (const { file, owner } of files) {
		let m;
		try {
			m = JSON.parse(readFileSync(file, "utf8"));
		} catch (err) {
			errors.push(`${relative(root, file)}: ${err.message}`);
			continue;
		}
		const problems = validateManifest(m);
		if (problems.length) {
			errors.push(`${relative(root, file)}: ${problems.join("; ")}`);
			continue;
		}
		const dir = relative(root, dirname(file)).split("\\").join("/") + "/";
		games.push({
			id: owner ? `${owner}/${m.id}` : m.id,
			name: m.name,
			blurb: m.blurb ?? "",
			// The portal's card: a title in ordinary case and a longer pitch.
			title: m.title ?? m.name,
			description: m.description ?? m.blurb ?? "",
			shape: m.shape ?? "free",
			seats: m.seats,
			players: m.players ?? null,
			bots: m.bots !== false && m.kind !== "shared",
			local: m.kind === "local",
			kind: m.kind,
			tags: m.tags ?? [],
			preview: m.preview ? dir + m.preview : null,
			path: dir,
			entry: m.entry,
			app: m.app ?? null,
			ownColours: !!m.ownColours,
			author: m.author,
			repo: m.repo,
			community: !!owner,
		});
	}
	const seen = new Set();
	for (const g of games) {
		if (seen.has(g.id)) errors.push(`duplicate game id: ${g.id}`);
		seen.add(g.id);
	}
	if (errors.length) throw new Error(errors.join("\n"));
	return games;
}

/**
 * A contributor's card from their repo's contributor.json (optional): the
 * login is the repo owner's, the rest is theirs to say. Throws when invalid.
 */
export function contributorEntry(login, repo, data, commit = null) {
	if (data) {
		const problems = validateContributor(data);
		if (problems.length) throw new Error(`contributor.json for ${login}: ${problems.join("; ")}`);
	}
	return {
		login,
		repos: [repo],
		// The pinned commit of each listed repo, for "Propose update" (lib/propose.js).
		pins: commit ? { [repo]: commit } : {},
		name: data?.name ?? null,
		bio: data?.bio ?? null,
		location: data?.location ?? null,
		links: data?.links ?? [],
	};
}

/** The classic script that registers `games` (appending to CATALOG). */
export function catalogScript(games, { file, source, contributors = [] }) {
	return `// ${file} — GENERATED by ${source}; do not edit.
// Framed games' manifests. Registering here only lists a game: its code
// loads into a sandboxed frame when picked (lib/bridge.js). CONTRIBUTORS is
// each repo owner's card (contributor.json), for contributors.html.

window.NeonArcade = window.NeonArcade || {};
NeonArcade.CONTRIBUTORS = (NeonArcade.CONTRIBUTORS || []).concat(${JSON.stringify(contributors, null, "\t")});
NeonArcade.CATALOG = (NeonArcade.CATALOG || []).concat(${JSON.stringify(games, null, "\t")});
// The party registers them; the portal only reads CATALOG to draw its cards.
for (const g of ${JSON.stringify(games.map((g) => g.id))}) {
	const def = NeonArcade.CATALOG.find((c) => c.id === g);
	NeonArcade.registerFramedGame?.({ ...def, base: new URL(def.path, document.baseURI).href });
}
`;
}
