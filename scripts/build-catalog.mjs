// scripts/build-catalog.mjs — every framed game's manifest, as one script.
//
// The party shell has to know a game's name, seats and shape before it loads
// the game (to list it, check the roster, offer bots), and a static site cannot
// list a folder at runtime. So the manifests are gathered here into
// lib/catalog.js, which party.html loads like any other lib file.
//
//   node scripts/build-catalog.mjs          write lib/catalog.js
//   node scripts/build-catalog.mjs --check  fail if it is out of date
//
// Sources: games/<id>/game.json (first-party, this repo) and
// community/<owner>/<repo>/<path>/game.json (pinned outside repos, fetched by
// scripts/fetch-community.mjs). Community ids are namespaced <owner>/<id>.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateManifest } from "./manifest.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "lib", "catalog.js");

function manifests() {
	const found = [];
	for (const id of readdirSync(join(ROOT, "games")).sort()) {
		const file = join(ROOT, "games", id, "game.json");
		if (existsSync(file)) found.push({ file, owner: null });
	}
	const community = join(ROOT, "community");
	if (existsSync(community)) {
		for (const owner of readdirSync(community).sort()) {
			for (const repo of readdirSync(join(community, owner)).sort()) {
				const pin = join(community, owner, repo, "pin.json");
				if (!existsSync(pin)) continue;
				for (const path of JSON.parse(readFileSync(pin, "utf8")).games) {
					found.push({ file: join(community, owner, repo, path, "game.json"), owner });
				}
			}
		}
	}
	return found;
}

const games = [];
const errors = [];
for (const { file, owner } of manifests()) {
	const m = JSON.parse(readFileSync(file, "utf8"));
	const problems = validateManifest(m);
	if (problems.length) {
		errors.push(`${relative(ROOT, file)}: ${problems.join("; ")}`);
		continue;
	}
	const dir = relative(ROOT, dirname(file)).split("\\").join("/") + "/";
	games.push({
		id: owner ? `${owner}/${m.id}` : m.id,
		name: m.name,
		blurb: m.blurb ?? "",
		shape: m.shape ?? "free",
		seats: m.seats,
		bots: m.bots !== false,
		local: m.kind === "local",
		kind: m.kind,
		tags: m.tags ?? [],
		preview: m.preview ? dir + m.preview : null,
		path: dir,
		entry: m.entry,
		author: m.author,
		repo: m.repo,
		community: !!owner,
	});
}
if (errors.length) {
	console.error(errors.join("\n"));
	process.exit(1);
}
const ids = new Set();
for (const g of games) {
	if (ids.has(g.id)) {
		console.error(`duplicate game id: ${g.id}`);
		process.exit(1);
	}
	ids.add(g.id);
}

const body = `// lib/catalog.js — GENERATED by scripts/build-catalog.mjs; do not edit.
// Every framed game's manifest. Registering here only lists the game: its code
// loads into a sandboxed frame when picked (lib/bridge.js).

window.NeonArcade = window.NeonArcade || {};
NeonArcade.CATALOG = ${JSON.stringify(games, null, "\t")};
for (const g of NeonArcade.CATALOG) {
	NeonArcade.registerFramedGame({ ...g, base: new URL(g.path, document.baseURI).href });
}
`;

if (process.argv.includes("--check")) {
	const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
	if (now !== body) {
		console.error("lib/catalog.js is out of date: run `just catalog`");
		process.exit(1);
	}
	console.log(`catalog: ${games.length} games, up to date`);
} else {
	writeFileSync(OUT, body);
	console.log(`catalog: ${games.length} games → lib/catalog.js`);
}
